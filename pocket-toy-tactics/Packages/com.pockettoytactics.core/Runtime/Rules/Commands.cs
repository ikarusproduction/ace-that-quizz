using System.Collections.Generic;

namespace PocketToyTactics.Core
{
    public enum CommandType
    {
        /// <summary>Turn action: draw 2 troops (or 1 if only one fits / remains).</summary>
        Draw,
        /// <summary>Turn action or Cap'taine extra placement: TileId on NodeId.</summary>
        Place,
        /// <summary>Answer to a pending decision (NodeId, TileId or Index depending on the decision; nothing to accept).</summary>
        Choose,
        /// <summary>Decline an optional effect.</summary>
        Skip,
    }

    /// <summary>
    /// A player intent. Commands are the only way to change a GameState, are fully serializable,
    /// and replaying the same commands from the same seed always reproduces the same game.
    /// </summary>
    public sealed class Command
    {
        public CommandType Type;
        public Side Player;
        public int TileId = -1;
        public string NodeId;
        public int Index = -1;
        /// <summary>Unique id generated by the sender (network de-duplication). Not used by the rules.</summary>
        public string ActionId;

        public static Command Draw(Side p) => new Command { Type = CommandType.Draw, Player = p };
        public static Command Place(Side p, int tile, string node) => new Command { Type = CommandType.Place, Player = p, TileId = tile, NodeId = node };
        public static Command Accept(Side p) => new Command { Type = CommandType.Choose, Player = p };
        public static Command ChooseNode(Side p, string node) => new Command { Type = CommandType.Choose, Player = p, NodeId = node };
        public static Command ChooseTile(Side p, int tile) => new Command { Type = CommandType.Choose, Player = p, TileId = tile };
        public static Command ChooseIndex(Side p, int index) => new Command { Type = CommandType.Choose, Player = p, Index = index };
        public static Command Skip(Side p) => new Command { Type = CommandType.Skip, Player = p };

        public Command Clone() => (Command)MemberwiseClone();

        public override string ToString()
        {
            switch (Type)
            {
                case CommandType.Draw: return Player + " draw";
                case CommandType.Place: return Player + " place #" + TileId + " on " + NodeId;
                case CommandType.Skip: return Player + " skip";
                default:
                    if (NodeId != null) return Player + " choose node " + NodeId;
                    if (TileId >= 0) return Player + " choose tile #" + TileId;
                    if (Index >= 0) return Player + " choose slot " + Index;
                    return Player + " accept";
            }
        }

        public Dictionary<string, object> ToJson()
        {
            var d = new Dictionary<string, object> { ["t"] = Type.ToString(), ["p"] = Player.Key() };
            if (TileId >= 0) d["tile"] = TileId;
            if (NodeId != null) d["node"] = NodeId;
            if (Index >= 0) d["idx"] = Index;
            if (ActionId != null) d["aid"] = ActionId;
            return d;
        }

        public static Command FromJson(Dictionary<string, object> d)
        {
            var typeName = d.Str("t");
            if (!System.Enum.TryParse(typeName, out CommandType type)) throw new System.FormatException("bad command type " + typeName);
            return new Command
            {
                Type = type,
                Player = SideExt.ParseSide(d.Str("p")),
                TileId = d.Int("tile", -1),
                NodeId = d.Str("node"),
                Index = d.Int("idx", -1),
                ActionId = d.Str("aid"),
            };
        }
    }

    public enum RuleError
    {
        None,
        GameOver,
        NotYourTurn,
        WrongPhase,
        RackFull,
        ReserveEmpty,
        TileNotInRack,
        TileLaidDown,
        UnknownNode,
        OwnHq,
        NotConnected,
        TooWeak,
        StrengthNotAllowed,
        InvalidTarget,
        NotOptional,
        InvalidCommand,
    }

    public static class RuleMessages
    {
        /// <summary>Player-facing explanation (French) of why an action is impossible.</summary>
        public static string Fr(RuleError e)
        {
            switch (e)
            {
                case RuleError.None: return "Action possible.";
                case RuleError.GameOver: return "La partie est terminée.";
                case RuleError.NotYourTurn: return "Ce n'est pas votre tour.";
                case RuleError.WrongPhase: return "Cette action n'est pas possible maintenant.";
                case RuleError.RackFull: return "Votre support contient déjà 8 troupes.";
                case RuleError.ReserveEmpty: return "Votre réserve est vide.";
                case RuleError.TileNotInRack: return "Cette troupe n'est pas sur votre support.";
                case RuleError.TileLaidDown: return "Cette troupe est couchée : elle ne peut pas être placée ce tour-ci.";
                case RuleError.UnknownNode: return "Emplacement inconnu.";
                case RuleError.OwnHq: return "Vous ne pouvez jamais placer de troupe sur votre propre Q.G.";
                case RuleError.NotConnected: return "Cet emplacement n'est pas relié à votre Q.G. par des bases que vous occupez.";
                case RuleError.TooWeak: return "La troupe adverse visible est aussi forte ou plus forte que la vôtre.";
                case RuleError.StrengthNotAllowed: return "Cette valeur de troupe n'est pas autorisée sur cet emplacement.";
                case RuleError.InvalidTarget: return "Cible invalide pour cet effet.";
                case RuleError.NotOptional: return "Cet effet est obligatoire.";
                default: return "Action invalide.";
            }
        }
    }
}
